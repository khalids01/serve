import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../packages/contracts/src/index.ts", import.meta.url);
const target = new URL("../../src/lib/v1-contracts.ts", import.meta.url);
const content = `// Generated by npm_pkg/scripts/sync-contracts.mjs. Do not edit.\n${readFileSync(source, "utf8")}`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== content)
    throw new Error("Backend contracts are stale. Run bun run contracts:sync.");
} else writeFileSync(target, content);
