import { readFileSync, writeFileSync } from "node:fs";

const examples = {
  serverUpload: "upload.mjs",
  connectionCheck: "check-serve.mjs",
  consumerEnv: ".env.example",
  nextServerClient: "lib/file-server.ts",
  nextTokenRoute: "app/api/file-server/token/route.ts",
  nextFilesClient: "app/files/files-client.tsx",
  nextFilesPage: "app/files/page.tsx",
  browserClient: "browser-client.ts",
  serverOperations: "server-operations.ts",
  genericTokenRoute: "token-handler.ts",
  reactAdvanced: "app/files/custom-files.tsx",
};
const snippets = Object.fromEntries(
  Object.entries(examples).map(([key, path]) => [
    key,
    readFileSync(
      new URL(`../examples/quickstart/${path}`, import.meta.url),
      "utf8",
    ).trim(),
  ]),
);
const { version } = JSON.parse(
  readFileSync(
    new URL("../packages/server/package.json", import.meta.url),
    "utf8",
  ),
);
const template = readFileSync(
  new URL("../docs/integration-guide.template.md", import.meta.url),
  "utf8",
);
const guide = template
  .replace(/\{\{sdkVersion\}\}/g, version)
  .replace(/\{\{snippet:(\w+)\}\}/g, (_match, key) => {
    if (!(key in snippets)) throw new Error(`Unknown docs snippet ${key}`);
    return snippets[key];
  });
const sections = [...guide.matchAll(/^## (.+)$/gm)].map(([, title]) => ({
  title,
  id: title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, ""),
}));
if (new Set(sections.map((section) => section.id)).size !== sections.length)
  throw new Error("Duplicate documentation heading");
function sync(path, content) {
  const target = new URL(path, import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== content)
      throw new Error(
        `Documentation is stale: ${path}. Run bun run docs:sync.`,
      );
  } else writeFileSync(target, content);
}
const banner = "// Generated by npm_pkg/scripts/sync-docs.mjs. Do not edit.\n";
sync(
  "../../src/features/docs/sdk-snippets.ts",
  banner +
    "export const sdkSnippets = " +
    JSON.stringify(snippets, null, 2) +
    " as const;\n",
);
sync("../../docs/integration-guide.md", guide);
sync(
  "../../src/features/docs/integration-guide.ts",
  banner +
    "export const sdkVersion = " +
    JSON.stringify(version) +
    ";\nexport const integrationSections = " +
    JSON.stringify(sections, null, 2) +
    " as const;\nexport const integrationGuide = " +
    JSON.stringify(guide) +
    ";\n",
);
